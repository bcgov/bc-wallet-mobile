@testable import BcscCoreTestable
import XCTest

/// The PIN bridge methods now take the account's ID and issuer from JS instead of reading the account file.
/// These pin that `PINService`, keyed only by those two values, finds the same secrets existing users have.
final class PINServiceAccountParamsTests: XCTestCase {
  private let issuer = "https://idsit.gov.bc.ca"
  private let accountID = "4D38CCF7-F465-4D05-B7CC-2FED125AF3E8"

  private var keychain = MockPINKeychainService()
  private var pinService = PINService()

  override func setUp() {
    super.setUp()
    keychain = MockPINKeychainService()
    pinService = PINService(keychainService: keychain)
  }

  /// Existing users' secrets are stored under this ID; changing it would orphan their PINs.
  func testSecretIDIsIssuerDotAccountID() {
    XCTAssertEqual(PINSecret.composeID(issuer: issuer, accountID: accountID), "\(issuer).\(accountID)")
  }

  func testSetPINStoresUnderTheGivenIssuerAndAccount() throws {
    let walletKey = try pinService.setPIN(issuer: issuer, accountID: accountID, pin: "123456")

    let stored = try XCTUnwrap(keychain.storedSecrets["\(issuer).\(accountID)"])
    XCTAssertEqual(stored.key, walletKey)
    XCTAssertFalse(stored.isAutoGenerated)
  }

  func testVerifyPINReturnsTheWalletKeyOnlyForTheRightPINAndAccount() throws {
    let walletKey = try pinService.setPIN(issuer: issuer, accountID: accountID, pin: "123456")

    XCTAssertEqual(pinService.verifyPINAndGetHash(issuer: issuer, accountID: accountID, pin: "123456"), walletKey)
    XCTAssertNil(pinService.verifyPINAndGetHash(issuer: issuer, accountID: accountID, pin: "654321"))
    XCTAssertNil(pinService.verifyPINAndGetHash(issuer: issuer, accountID: UUID().uuidString, pin: "123456"))
    XCTAssertNil(pinService.verifyPINAndGetHash(issuer: "https://idqa.gov.bc.ca", accountID: accountID, pin: "123456"))
  }

  func testHasPINIsOnlyWhetherTheSecretExists() throws {
    XCTAssertFalse(pinService.hasPIN(issuer: issuer, accountID: accountID))

    try pinService.setPIN(issuer: issuer, accountID: accountID, pin: "123456", isAutoGenerated: true)

    XCTAssertTrue(pinService.hasPIN(issuer: issuer, accountID: accountID))
    XCTAssertFalse(pinService.hasPIN(issuer: issuer, accountID: UUID().uuidString))
  }

  /// `hasPINSet` used `Account.hasPINSetup`, which also required a PIN security method. The new check
  /// ignores the method: a device-auth account with an auto-generated PIN now reports true.
  func testHasPINDiffersFromHasPINSetupOnlyByTheSecurityMethod() throws {
    try pinService.setPIN(issuer: issuer, accountID: accountID, pin: "123456")

    for method in [AccountSecurityMethod.pinNoDeviceAuth, .pinWithDeviceAuth, .deviceAuth] {
      let account = Account(id: accountID, clientID: "client-1", issuer: issuer, securityMethod: method)
      let hasPINSetup = account.hasPINSetup(keychainService: keychain)
      XCTAssertEqual(hasPINSetup, method.isPIN, "\(method)")
    }
    XCTAssertTrue(pinService.hasPIN(issuer: issuer, accountID: accountID))
  }

  func testDeletePINRemovesOnlyThatSecretAndToleratesAMissingOne() throws {
    let otherAccountID = UUID().uuidString
    try pinService.setPIN(issuer: issuer, accountID: accountID, pin: "123456")
    try pinService.setPIN(issuer: issuer, accountID: otherAccountID, pin: "123456")

    try pinService.deletePIN(issuer: issuer, accountID: accountID)
    try pinService.deletePIN(issuer: issuer, accountID: accountID)

    XCTAssertFalse(pinService.hasPIN(issuer: issuer, accountID: accountID))
    XCTAssertTrue(pinService.hasPIN(issuer: issuer, accountID: otherAccountID))
  }

  func testIsPINAutoGenerated() throws {
    XCTAssertFalse(pinService.isPINAutoGenerated(issuer: issuer, accountID: accountID))

    try pinService.setPIN(issuer: issuer, accountID: accountID, pin: "123456", isAutoGenerated: true)
    XCTAssertTrue(pinService.isPINAutoGenerated(issuer: issuer, accountID: accountID))

    try pinService.setPIN(issuer: issuer, accountID: accountID, pin: "123456", isAutoGenerated: false)
    XCTAssertFalse(pinService.isPINAutoGenerated(issuer: issuer, accountID: accountID))
  }

  /// unlockWithDeviceSecurity's v3 path: no hash yet, so it creates an auto-generated PIN for these params.
  func testV3DeviceAuthMigrationCreatesAnAutoGeneratedPINForTheParams() throws {
    XCTAssertNil(pinService.getPINHash(issuer: issuer, accountID: accountID))

    let walletKey = try pinService.setPIN(issuer: issuer, accountID: accountID, pin: "246810", isAutoGenerated: true)

    let hash = try XCTUnwrap(pinService.getPINHash(issuer: issuer, accountID: accountID))
    XCTAssertEqual(hash.hash, walletKey)
    XCTAssertTrue(hash.isAutoGenerated)
  }
}
