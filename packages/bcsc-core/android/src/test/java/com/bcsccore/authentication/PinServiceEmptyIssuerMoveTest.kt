package com.bcsccore.authentication

import android.content.Context
import android.content.SharedPreferences
import androidx.security.crypto.EncryptedSharedPreferences
import androidx.security.crypto.MasterKeys
import com.bcsccore.storage.NativeCompatiblePinStorage
import io.mockk.every
import io.mockk.mockkStatic
import io.mockk.unmockkStatic
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.RuntimeEnvironment
import org.robolectric.annotation.Config
import org.robolectric.shadows.ShadowLog
import java.io.File

/**
 * A PIN stored under the empty-issuer alias ".<accountId>" (the old issuer lookup's fallback) is moved to
 * "<issuer>.<accountId>" the first time it is used. Robolectric has no AndroidKeyStore, so EncryptedSharedPreferences
 * is stood in for by plain prefs with the same file names; the KDF and the storage logic are real.
 * API 34: deleting prefs files needs API 24, the module's minSdk.
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
class PinServiceEmptyIssuerMoveTest {
    private val app = RuntimeEnvironment.getApplication()
    private lateinit var pinService: PinService
    private lateinit var storage: NativeCompatiblePinStorage

    private val issuer = "https://idsit.gov.bc.ca/device/"
    private val uuid = "123e4567-e89b-42d3-a456-426614174000"
    private val emptyIssuerAlias = ".$uuid"
    private val properAlias = "$issuer.$uuid"

    // Opening the proper alias's prefs fails while this is set, as a broken keystore would
    private var failProperAlias = false

    @Before
    fun setUp() {
        mockkStatic(MasterKeys::class)
        every { MasterKeys.getOrCreate(any()) } returns "master-key"
        mockkStatic(EncryptedSharedPreferences::class)
        every {
            EncryptedSharedPreferences.create(any<String>(), any<String>(), any<Context>(), any(), any())
        } answers {
            val fileName = firstArg<String>()
            if (failProperAlias && fileName == NativeCompatiblePinStorage.prefsFileName(properAlias)) {
                throw IllegalStateException("keystore unavailable")
            }
            app.getSharedPreferences(fileName, Context.MODE_PRIVATE) as SharedPreferences
        }
        ShadowLog.clear()

        pinService = PinService(app)
        storage = NativeCompatiblePinStorage(app)
    }

    @After
    fun tearDown() {
        unmockkStatic(EncryptedSharedPreferences::class)
        unmockkStatic(MasterKeys::class)
    }

    private fun prefsFile(alias: String) =
        File(app.dataDir, "shared_prefs/${NativeCompatiblePinStorage.prefsFileName(alias)}.xml")

    private fun storeEmptyIssuerPin(
        pin: String,
        isAutoGenerated: Boolean = false,
    ): String = storage.setPin(emptyIssuerAlias, pin, isAutoGenerated)!!.key

    private fun moveLogCount() =
        ShadowLog.getLogsForTag("PinService").count { it.msg == "[PinService] moved PIN from empty-issuer alias" }

    @Test
    fun `verify moves the PIN and keeps its wallet key`() {
        val walletKey = storeEmptyIssuerPin("123456")

        assertEquals(Pair(true, walletKey), pinService.validatePINReturningHash(uuid, issuer, "123456"))

        assertFalse("old file deleted", prefsFile(emptyIssuerAlias).exists())
        assertTrue(storage.hasStoredEntries(properAlias))
        assertEquals(Pair(true, walletKey), pinService.validatePINReturningHash(uuid, issuer, "123456"))
        assertEquals(Pair(false, null), pinService.validatePINReturningHash(uuid, issuer, "000000"))
        assertEquals("moved once", 1, moveLogCount())
    }

    @Test
    fun `unlock's hash read moves an auto-generated PIN unchanged`() {
        val walletKey = storeEmptyIssuerPin("482910", isAutoGenerated = true)

        assertEquals(Pair(walletKey, true), pinService.getPINHash(uuid, issuer))

        assertTrue(pinService.isPINAutoGenerated(uuid, issuer))
        assertFalse(prefsFile(emptyIssuerAlias).exists())
        assertEquals(1, moveLogCount())
    }

    @Test
    fun `hasPIN moves the PIN`() {
        storeEmptyIssuerPin("123456")

        assertTrue(pinService.hasPIN(uuid, issuer))

        assertFalse(prefsFile(emptyIssuerAlias).exists())
        assertTrue(pinService.validatePINReturningHash(uuid, issuer, "123456").first)
    }

    @Test
    fun `nothing moves when the proper alias already has a PIN`() {
        pinService.setPINReturningHash(uuid, issuer, "111111", removeEmptyIssuerPin = false)
        storeEmptyIssuerPin("222222")

        assertFalse(pinService.validatePINReturningHash(uuid, issuer, "222222").first)
        assertTrue(pinService.validatePINReturningHash(uuid, issuer, "111111").first)

        assertTrue("empty-issuer PIN untouched", storage.hasStoredEntries(emptyIssuerAlias))
        assertEquals(0, moveLogCount())
    }

    @Test
    fun `a failed move leaves the old PIN in place and the next attempt moves it`() {
        val walletKey = storeEmptyIssuerPin("123456")
        failProperAlias = true

        assertEquals(Pair(false, null), pinService.validatePINReturningHash(uuid, issuer, "123456"))
        assertNull(pinService.getPINHash(uuid, issuer))

        assertTrue("old PIN kept", storage.hasStoredEntries(emptyIssuerAlias))
        assertFalse("nothing half-written", storage.hasStoredEntries(properAlias))
        assertEquals(0, moveLogCount())

        failProperAlias = false
        assertEquals(Pair(true, walletKey), pinService.validatePINReturningHash(uuid, issuer, "123456"))
        assertFalse(prefsFile(emptyIssuerAlias).exists())
        assertEquals(1, moveLogCount())
    }

    @Test
    fun `setting a PIN deletes the empty-issuer PIN so it can't be moved later`() {
        storeEmptyIssuerPin("222222")

        pinService.setPINReturningHash(uuid, issuer, "999999")

        assertFalse(prefsFile(emptyIssuerAlias).exists())
        assertFalse(pinService.validatePINReturningHash(uuid, issuer, "222222").first)
        assertTrue(pinService.validatePINReturningHash(uuid, issuer, "999999").first)
    }

    @Test
    fun `the unlock mint path keeps an empty-issuer PIN it may be replacing`() {
        storeEmptyIssuerPin("222222")

        pinService.setupDeviceSecurityPIN(uuid, issuer, "482910", removeEmptyIssuerPin = false)

        assertTrue(storage.hasStoredEntries(emptyIssuerAlias))
    }

    @Test
    fun `removePIN deletes both the proper and the empty-issuer PIN`() {
        pinService.setPINReturningHash(uuid, issuer, "111111", removeEmptyIssuerPin = false)
        storeEmptyIssuerPin("222222")

        pinService.removePIN(uuid, issuer)

        assertFalse(prefsFile(properAlias).exists())
        assertFalse(prefsFile(emptyIssuerAlias).exists())
        assertFalse(pinService.hasPIN(uuid, issuer))
    }
}
