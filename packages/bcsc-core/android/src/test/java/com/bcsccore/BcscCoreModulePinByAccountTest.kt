package com.bcsccore

import com.bcsccore.storage.NativeCompatiblePinStorage
import com.bcsccore.storage.NativePinSecret
import com.facebook.react.bridge.Arguments
import com.facebook.react.bridge.JavaOnlyMap
import com.facebook.react.bridge.Promise
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.bridge.ReadableMap
import io.mockk.every
import io.mockk.mockk
import io.mockk.mockkConstructor
import io.mockk.mockkStatic
import io.mockk.unmockkConstructor
import io.mockk.unmockkStatic
import io.mockk.verify
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner

/**
 * The PIN methods find the PIN from the account ID and issuer they are given, under the same
 * "$issuer.$accountId" alias as before, so a PIN set by an earlier version still matches. No accounts file exists
 * in these tests, and none may be written. PIN storage needs the Android keystore, so it is an in-memory stand-in.
 */
@RunWith(RobolectricTestRunner::class)
class BcscCoreModulePinByAccountTest {
    @get:Rule
    val tempFolder = TemporaryFolder()

    private lateinit var module: BcscCoreModule

    private val issuer = "https://idsit.gov.bc.ca/device/"
    private val accountUuid = "123e4567-e89b-42d3-a456-426614174000"
    private val alias = "$issuer.$accountUuid"

    private val secrets = mutableMapOf<String, Pair<String, Boolean>>()

    @Before
    fun setUp() {
        mockkStatic(Arguments::class)
        every { Arguments.createMap() } answers { JavaOnlyMap() }

        mockkConstructor(NativeCompatiblePinStorage::class)
        every { anyConstructed<NativeCompatiblePinStorage>().checkForOldFormatPin(any()) } returns false
        every { anyConstructed<NativeCompatiblePinStorage>().removeOldFormatPin(any()) } returns true
        every { anyConstructed<NativeCompatiblePinStorage>().moveSecret(any(), any()) } returns
            NativeCompatiblePinStorage.SecretMove.NOT_NEEDED
        every { anyConstructed<NativeCompatiblePinStorage>().deletePinFile(any()) } returns Unit
        every { anyConstructed<NativeCompatiblePinStorage>().setPin(any(), any(), any()) } answers {
            val key = "key-for-${secondArg<String>()}"
            secrets[firstArg()] = key to thirdArg()
            NativePinSecret(firstArg(), ByteArray(16), "PBKDF2WithHmacSHA256", key, thirdArg())
        }
        every { anyConstructed<NativeCompatiblePinStorage>().verifyPin(any(), any()) } answers {
            secrets[firstArg()]?.first == "key-for-${secondArg<String>()}"
        }
        every { anyConstructed<NativeCompatiblePinStorage>().getPinHash(any()) } answers { secrets[firstArg()] }
        every { anyConstructed<NativeCompatiblePinStorage>().hasPin(any()) } answers { firstArg<String>() in secrets }
        every { anyConstructed<NativeCompatiblePinStorage>().isPinAutoGenerated(any()) } answers {
            secrets[firstArg()]?.second ?: false
        }
        every { anyConstructed<NativeCompatiblePinStorage>().removePin(any()) } answers {
            secrets.remove(firstArg<String>())
            true
        }

        val context = mockk<ReactApplicationContext>(relaxed = true)
        every { context.filesDir } returns tempFolder.root
        module = BcscCoreModule(context)
    }

    @After
    fun tearDown() {
        unmockkConstructor(NativeCompatiblePinStorage::class)
        unmockkStatic(Arguments::class)
    }

    private fun resolved(call: (Promise) -> Unit): Any? {
        val promise = mockk<Promise>(relaxed = true)
        val values = mutableListOf<Any?>()
        call(promise)
        verify(exactly = 1) { promise.resolve(captureNullable(values)) }
        return values.single()
    }

    @Test
    fun `a PIN can be set, checked, verified and deleted with no accounts file`() {
        val setResult = resolved { module.setPIN(accountUuid, issuer, "123456", it) } as ReadableMap
        assertEquals(setOf(alias), secrets.keys)

        assertEquals(true, resolved { module.hasPINSet(accountUuid, issuer, it) })
        assertEquals(false, resolved { module.isPINAutoGenerated(accountUuid, issuer, it) })
        val verified = resolved { module.verifyPIN(accountUuid, issuer, "123456", it) } as ReadableMap
        assertTrue(verified.getBoolean("success"))
        assertEquals(setResult.getString("walletKey"), verified.getString("walletKey"))
        assertFalse(
            (resolved { module.verifyPIN(accountUuid, issuer, "000000", it) } as ReadableMap).getBoolean("success"),
        )

        assertEquals(true, resolved { module.deletePIN(accountUuid, issuer, it) })
        assertEquals(false, resolved { module.hasPINSet(accountUuid, issuer, it) })

        assertTrue("no account file may be written", tempFolder.root.listFiles().isNullOrEmpty())
    }

    @Test
    fun `a PIN stored under the existing alias is found from the params`() {
        secrets[alias] = "existing-wallet-key" to false

        val verified = resolved { module.verifyPIN(accountUuid, issuer, "anything", it) } as ReadableMap

        assertFalse(verified.getBoolean("success"))
        assertEquals(true, resolved { module.hasPINSet(accountUuid, issuer, it) })
        assertEquals(false, resolved { module.hasPINSet(accountUuid, "https://id.gov.bc.ca/device/", it) })
    }

    @Test
    fun `setupDeviceSecurity stores an auto-generated PIN for the given account`() {
        val result = resolved { module.setupDeviceSecurity(accountUuid, issuer, it) } as ReadableMap

        assertTrue(result.getBoolean("isAutoGenerated"))
        assertEquals(secrets.getValue(alias).first, result.getString("walletKey"))
        assertEquals(true, resolved { module.isPINAutoGenerated(accountUuid, issuer, it) })
        assertTrue(tempFolder.root.listFiles().isNullOrEmpty())
    }

    @Test
    fun `every PIN method rejects E_INVALID_PARAMETERS for an empty accountId or issuer`() {
        val calls: List<(String, String, Promise) -> Unit> =
            listOf(
                { id, iss, p -> module.setPIN(id, iss, "123456", p) },
                { id, iss, p -> module.verifyPIN(id, iss, "123456", p) },
                { id, iss, p -> module.deletePIN(id, iss, p) },
                { id, iss, p -> module.hasPINSet(id, iss, p) },
                { id, iss, p -> module.setupDeviceSecurity(id, iss, p) },
                { id, iss, p -> module.unlockWithDeviceSecurity(id, iss, null, p) },
                { id, iss, p -> module.isPINAutoGenerated(id, iss, p) },
            )

        for (call in calls) {
            for ((id, iss) in listOf("" to issuer, accountUuid to "")) {
                val promise = mockk<Promise>(relaxed = true)
                call(id, iss, promise)
                verify(exactly = 1) { promise.reject("E_INVALID_PARAMETERS", "accountId and issuer are required") }
            }
        }
        assertTrue(secrets.isEmpty())
    }
}
