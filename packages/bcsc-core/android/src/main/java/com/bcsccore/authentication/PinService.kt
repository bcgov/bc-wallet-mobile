package com.bcsccore.authentication

import android.content.Context
import android.util.Log
import com.bcsccore.storage.NativeCompatiblePinStorage

/**
 * PinService wrapper that uses native-compatible PIN storage.
 * This ensures rollback compatibility with ias-android.
 *
 * This class provides the same interface as the original PinService
 * but uses NativeCompatiblePinStorage under the hood for:
 * - EncryptedSharedPreferences (matching native)
 * - Native-compatible PBKDF2 parameters (210k iterations, SHA256)
 * - Native-compatible key naming conventions
 *
 * PIN aliases use the v3 format "$issuer.$accountId" to remain compatible
 * during v3→v4 migration. Callers pass the account's issuer URL exactly as stored on the account.
 */
class PinService(
    private val context: Context,
) {
    companion object {
        private const val TAG = "PinService"
    }

    private val nativePinStorage: NativeCompatiblePinStorage by lazy {
        NativeCompatiblePinStorage(context)
    }

    // Outputs {issuer}.{account}
    // e.g. "https://id.gov.bc.ca/device/.1234-5678-9012"
    private fun buildAlias(
        accountId: String,
        issuer: String,
    ): String = "$issuer.$accountId"

    // Where the old issuer lookup stored a PIN when it couldn't find the account
    private fun emptyIssuerAlias(accountId: String): String = buildAlias(accountId, "")

    /**
     * The alias to use for an existing PIN. A PIN stored under an empty issuer is moved there first, once; if the
     * move fails it stays where it was and is retried on the next call.
     */
    private fun aliasForExistingPin(
        accountId: String,
        issuer: String,
    ): String {
        val alias = buildAlias(accountId, issuer)
        if (issuer.isEmpty()) {
            return alias
        }
        when (nativePinStorage.moveSecret(emptyIssuerAlias(accountId), alias)) {
            NativeCompatiblePinStorage.SecretMove.MOVED -> {
                Log.i(TAG, "[PinService] moved PIN from empty-issuer alias")
            }

            NativeCompatiblePinStorage.SecretMove.FAILED -> {
                Log.w(TAG, "[PinService] could not move PIN from empty-issuer alias; will retry")
            }

            NativeCompatiblePinStorage.SecretMove.NOT_NEEDED -> {
                Unit
            }
        }
        return alias
    }

    private fun removeEmptyIssuerPin(accountId: String) {
        val alias = emptyIssuerAlias(accountId)
        nativePinStorage.removeOldFormatPin(alias)
        nativePinStorage.deletePinFile(alias)
    }

    /**
     * Checks if a PIN is set for the given account ID.
     */
    fun hasPIN(
        accountId: String,
        issuer: String,
    ): Boolean {
        val alias = aliasForExistingPin(accountId, issuer)
        val hasPin = nativePinStorage.hasPin(alias)
        Log.d(TAG, "hasPIN($accountId): $hasPin")
        return hasPin
    }

    /**
     * Sets a PIN for the given account ID and returns the hash.
     * Uses native-compatible storage format.
     *
     * @param accountId The account identifier
     * @param issuer The account's issuer
     * @param pin The PIN to set
     * @param isAutoGenerated Whether the PIN was auto-generated (for device security) or user-created
     * @param removeEmptyIssuerPin Whether to delete a PIN stored under an empty issuer once this one is saved
     * @return The PBKDF2 hash of the PIN for use as wallet key
     */
    fun setPINReturningHash(
        accountId: String,
        issuer: String,
        pin: String,
        isAutoGenerated: Boolean = false,
        removeEmptyIssuerPin: Boolean = true,
    ): String {
        val alias = buildAlias(accountId, issuer)
        Log.d(TAG, "setPINReturningHash for account: $accountId (isAutoGenerated: $isAutoGenerated)")

        // Check for old-format PIN and warn (can't migrate due to different crypto params)
        if (nativePinStorage.checkForOldFormatPin(alias)) {
            Log.w(TAG, "Old-format PIN found. Will be replaced with native-compatible format.")
            nativePinStorage.removeOldFormatPin(alias)
        }

        val pinSecret = nativePinStorage.setPin(alias, pin, isAutoGenerated)
        if (pinSecret == null) {
            throw RuntimeException("Failed to set PIN for account: $accountId")
        }

        // A stale empty-issuer PIN must not be moved over this one later
        if (removeEmptyIssuerPin && issuer.isNotEmpty()) {
            removeEmptyIssuerPin(accountId)
        }

        Log.d(TAG, "Successfully set PIN for account: $accountId")
        return pinSecret.key
    }

    /**
     * Sets up a device security PIN (auto-generated) and returns the hash.
     *
     * @param accountId The account identifier
     * @param issuer The account's issuer
     * @param pin The auto-generated PIN
     * @param removeEmptyIssuerPin Whether to delete a PIN stored under an empty issuer once this one is saved
     * @return The PBKDF2 hash of the PIN for use as wallet key
     */
    fun setupDeviceSecurityPIN(
        accountId: String,
        issuer: String,
        pin: String,
        removeEmptyIssuerPin: Boolean = true,
    ): String = setPINReturningHash(accountId, issuer, pin, isAutoGenerated = true, removeEmptyIssuerPin)

    /**
     * Validates a PIN and returns the hash if successful.
     *
     * @param accountId The account identifier
     * @param issuer The account's issuer
     * @param pin The PIN to validate
     * @return Pair of (isValid, hash) where hash is only present if valid
     */
    fun validatePINReturningHash(
        accountId: String,
        issuer: String,
        pin: String,
    ): Pair<Boolean, String?> {
        val alias = aliasForExistingPin(accountId, issuer)
        val isValid = nativePinStorage.verifyPin(alias, pin)
        Log.d(TAG, "validatePINReturningHash($accountId): $isValid")

        if (isValid) {
            val hashResult = nativePinStorage.getPinHash(alias)
            return Pair(true, hashResult?.first)
        }
        return Pair(false, null)
    }

    /**
     * Removes the PIN for the given account ID.
     */
    fun removePIN(
        accountId: String,
        issuer: String,
    ): Boolean {
        val alias = buildAlias(accountId, issuer)
        Log.d(TAG, "removePIN for account: $accountId")

        // Also remove old-format if exists
        nativePinStorage.removeOldFormatPin(alias)

        val removed = nativePinStorage.removePin(alias)
        if (issuer.isNotEmpty()) {
            removeEmptyIssuerPin(accountId)
        }
        return removed
    }

    /**
     * Gets the PIN hash (PBKDF2 derived key) for use as an Askar wallet key.
     *
     * @param accountId The account identifier
     * @param issuer The account's issuer
     * @return Pair of (hash, isAutoGenerated) or null if not found
     */
    fun getPINHash(
        accountId: String,
        issuer: String,
    ): Pair<String, Boolean>? {
        val alias = aliasForExistingPin(accountId, issuer)
        val result = nativePinStorage.getPinHash(alias)
        Log.d(TAG, "getPINHash($accountId): ${if (result != null) "found" else "not found"}")
        return result
    }

    /**
     * Checks if the stored PIN was auto-generated (for device security) or user-created.
     *
     * @param accountId The account identifier
     * @param issuer The account's issuer
     * @return true if PIN was auto-generated, false if user-created or not found
     */
    fun isPINAutoGenerated(
        accountId: String,
        issuer: String,
    ): Boolean {
        val alias = aliasForExistingPin(accountId, issuer)
        val isAutoGenerated = nativePinStorage.isPinAutoGenerated(alias)
        Log.d(TAG, "isPINAutoGenerated($accountId): $isAutoGenerated")
        return isAutoGenerated
    }
}
