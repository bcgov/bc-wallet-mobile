import { BCSCLoadingProvider } from '@/bcsc-theme/contexts/BCSCLoadingContext'
import { ErrorAlertProvider } from '@/contexts/ErrorAlertContext'
import { BasicAppContext } from '@mocks/helpers/app'
import { act, fireEvent, render, waitFor } from '@testing-library/react-native'
import React from 'react'
import { setPIN } from 'react-native-bcsc-core'
import { CreatePINScreen } from './CreatePINScreen'

const mockHandleSuccessfulAuth = jest.fn()

jest.mock('react-native-bcsc-core', () => ({
  canPerformDeviceAuthentication: jest.fn().mockResolvedValue(false),
  getAccount: jest.fn().mockResolvedValue(null),
  setAccount: jest.fn().mockResolvedValue(undefined),
  setPIN: jest.fn(),
  AccountSecurityMethod: {
    PinNoDeviceAuth: 'app_pin_no_device_authn',
    PinWithDeviceAuth: 'app_pin_has_device_authn',
    DeviceAuth: 'device_authentication',
  },
}))

jest.mock('@/bcsc-theme/hooks/useBCSCApiClient', () => ({
  useBCSCApiClient: () => ({
    endpoints: { issuer: 'https://mock-issuer' },
  }),
  useBCSCApiClientState: () => ({
    client: {},
    isClientReady: true,
  }),
}))

jest.mock('@/bcsc-theme/hooks/useSecureActions', () => ({
  __esModule: true,
  default: () => ({
    handleSuccessfulAuth: mockHandleSuccessfulAuth,
  }),
}))

jest.mock('@/bcsc-theme/api/hooks/useRegistrationApi', () => ({
  __esModule: true,
  default: () => ({
    register: jest.fn(),
  }),
}))

const mockNavigation = {
  navigate: jest.fn(),
  goBack: jest.fn(),
  dispatch: jest.fn(),
  setOptions: jest.fn(),
  reset: jest.fn(),
  isFocused: jest.fn(),
  canGoBack: jest.fn(),
  addListener: jest.fn(),
  removeListener: jest.fn(),
} as any

describe('CreatePINScreen snapshots', () => {
  beforeEach(() => {
    jest.clearAllMocks()
  })

  it('renders correctly', () => {
    const tree = render(
      <BasicAppContext>
        <ErrorAlertProvider>
          <BCSCLoadingProvider>
            <CreatePINScreen navigation={mockNavigation} />
          </BCSCLoadingProvider>
        </ErrorAlertProvider>
      </BasicAppContext>
    )
    expect(tree).toMatchSnapshot()
  })
})

describe('CreatePINScreen', () => {
  beforeEach(() => {
    jest.clearAllMocks()
  })

  it('completes onboarding from the button, which keeps spinning as the root slides the screen out', async () => {
    jest.mocked(setPIN).mockResolvedValueOnce({ success: true, walletKey: 'test-wallet-key', isAutoGenerated: false })
    let completeOnboarding!: () => void
    mockHandleSuccessfulAuth.mockReturnValueOnce(
      new Promise<void>((resolve) => {
        completeOnboarding = resolve
      })
    )

    const tree = render(
      <BasicAppContext>
        <ErrorAlertProvider>
          <BCSCLoadingProvider>
            <CreatePINScreen navigation={mockNavigation} />
          </BCSCLoadingProvider>
        </ErrorAlertProvider>
      </BasicAppContext>
    )
    const overlayShown = () =>
      tree.getByTestId('com.ariesbifold:id/BCSCLoadingProviderOverlay', { includeHiddenElements: true }).props
        .accessible

    const inputs = tree.getAllByAccessibilityHint('Enter your 6-digit PIN')
    fireEvent.changeText(inputs[0], '123456')
    fireEvent.changeText(inputs[1], '123456')
    fireEvent.press(tree.getByTestId('com.ariesbifold:id/IUnderstand'))
    await act(async () => {
      fireEvent.press(tree.getByTestId('com.ariesbifold:id/CreatePIN'))
    })

    await waitFor(() => expect(mockHandleSuccessfulAuth).toHaveBeenCalledWith('test-wallet-key'))
    // No waiting screen between this screen and the verify prompt
    expect(overlayShown()).toBe(false)
    expect(tree.getByTestId('com.ariesbifold:id/ButtonLoading')).toBeTruthy()

    await act(async () => {
      completeOnboarding()
    })

    expect(overlayShown()).toBe(false)
    expect(tree.getByTestId('com.ariesbifold:id/ButtonLoading')).toBeTruthy()
  })
})
