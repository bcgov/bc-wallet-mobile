import { BCSCLoadingProvider } from '@/bcsc-theme/contexts/BCSCLoadingContext'
import { clearPinAttempts } from '@/bcsc-theme/features/auth/services/pin-lockout-service'
import { BasicAppContext } from '@mocks/helpers/app'
import { act, fireEvent, render, waitFor } from '@testing-library/react-native'
import React from 'react'
import { setPIN } from 'react-native-bcsc-core'
import { PINEntryForm } from './PINEntryForm'

jest.mock('react-native-bcsc-core', () => ({
  setPIN: jest.fn(),
  canPerformDeviceAuthentication: jest.fn().mockResolvedValue(false),
  getAccount: jest.fn().mockResolvedValue({ clientID: 'test-client-id', issuer: 'https://mock-issuer' }),
  setAccount: jest.fn().mockResolvedValue(undefined),
  isBcscNativeError: jest.fn().mockReturnValue(false),
  BcscNativeErrorCodes: {
    KEYPAIR_GENERATION_FAILED: 'E_KEYPAIR_GENERATION_FAILED',
  },
  AccountSecurityMethod: {
    PinNoDeviceAuth: 'app_pin_no_device_authn',
    PinWithDeviceAuth: 'app_pin_has_device_authn',
    DeviceAuth: 'device_authentication',
  },
}))

jest.mock('@/bcsc-theme/features/auth/services/pin-lockout-service', () => ({
  clearPinAttempts: jest.fn().mockResolvedValue(undefined),
}))

jest.mock('@/bcsc-theme/hooks/useBCSCApiClient', () => ({
  useBCSCApiClient: () => ({
    endpoints: { issuer: 'https://mock-issuer' },
  }),
  useBCSCApiClientState: () => ({
    client: {},
    isClientReady: true,
  }),
}))

jest.mock('@/bcsc-theme/api/hooks/useRegistrationApi', () => ({
  __esModule: true,
  default: () => ({
    register: jest.fn().mockResolvedValue(undefined),
  }),
}))

describe('PINEntryForm', () => {
  const mockSetPIN = jest.mocked(setPIN)
  const mockClearPinAttempts = jest.mocked(clearPinAttempts)
  const mockOnSuccess = jest.fn()

  it('renders correctly with create and confirm PIN fields', () => {
    const tree = render(
      <BasicAppContext>
        <BCSCLoadingProvider>
          <PINEntryForm onSuccess={mockOnSuccess} creatingNewPIN={true} />
        </BCSCLoadingProvider>
      </BasicAppContext>
    )

    expect(tree.getByText('BCSC.PIN.CreatePIN')).toBeTruthy()
    expect(tree.getByText('BCSC.PIN.ConfirmPIN')).toBeTruthy()
    expect(tree.getByText('BCSC.PIN.ThisPINIsUnique')).toBeTruthy()
    expect(tree.getByText(/BCSC\.PIN\.RememberPINWarning/)).toBeTruthy()
    expect(tree.getByText(/BCSC\.PIN\.RememberPINDescription/)).toBeTruthy()
    expect(tree).toMatchSnapshot()
  })

  it('uses custom translation prefix when provided', () => {
    const tree = render(
      <BasicAppContext>
        <BCSCLoadingProvider>
          <PINEntryForm onSuccess={mockOnSuccess} translationPrefix="Custom.Prefix" creatingNewPIN={true} />
        </BCSCLoadingProvider>
      </BasicAppContext>
    )

    expect(tree.getByText('Custom.Prefix.CreatePIN')).toBeTruthy()
    expect(tree.getByText('Custom.Prefix.ConfirmPIN')).toBeTruthy()
  })

  it('shows checkbox acknowledgment', () => {
    const tree = render(
      <BasicAppContext>
        <BCSCLoadingProvider>
          <PINEntryForm onSuccess={mockOnSuccess} creatingNewPIN={true} />
        </BCSCLoadingProvider>
      </BasicAppContext>
    )

    expect(tree.getByText('BCSC.PIN.IUnderstand')).toBeTruthy()
  })

  it('shows Create PIN button', () => {
    const tree = render(
      <BasicAppContext>
        <BCSCLoadingProvider>
          <PINEntryForm onSuccess={mockOnSuccess} creatingNewPIN={true} />
        </BCSCLoadingProvider>
      </BasicAppContext>
    )

    expect(tree.getByText('BCSC.PIN.CreatePINShort')).toBeTruthy()
  })

  it('shows continue button when creatingNewPIN is false', () => {
    const tree = render(
      <BasicAppContext>
        <BCSCLoadingProvider>
          <PINEntryForm onSuccess={mockOnSuccess} creatingNewPIN={false} />
        </BCSCLoadingProvider>
      </BasicAppContext>
    )

    expect(tree.getByText('Global.Continue')).toBeTruthy()
  })

  it('calls onSuccess with wallet key when PIN is set successfully', async () => {
    mockSetPIN.mockResolvedValue({
      success: true,
      walletKey: 'test-wallet-key',
      isAutoGenerated: false,
    })

    const tree = render(
      <BasicAppContext>
        <BCSCLoadingProvider>
          <PINEntryForm onSuccess={mockOnSuccess} creatingNewPIN={true} />
        </BCSCLoadingProvider>
      </BasicAppContext>
    )

    const inputs = tree.getAllByAccessibilityHint('Enter your 6-digit PIN')
    expect(inputs).toHaveLength(2) // Create and Confirm

    fireEvent.changeText(inputs[0], '123456')
    fireEvent.changeText(inputs[1], '123456')

    const checkbox = tree.getByTestId('com.ariesbifold:id/IUnderstand')
    fireEvent.press(checkbox)

    const button = tree.getByTestId('com.ariesbifold:id/CreatePIN')
    fireEvent.press(button)

    await waitFor(() => {
      expect(mockSetPIN).toHaveBeenCalledWith('123456')
      expect(mockOnSuccess).toHaveBeenCalledWith({
        success: true,
        walletKey: 'test-wallet-key',
      })
    })
  })

  it('forgets wrong attempts at the old PIN once the new PIN is set, before reporting success', async () => {
    mockSetPIN.mockResolvedValue({
      success: true,
      walletKey: 'test-wallet-key',
      isAutoGenerated: false,
    })

    const tree = render(
      <BasicAppContext>
        <BCSCLoadingProvider>
          <PINEntryForm onSuccess={mockOnSuccess} creatingNewPIN={true} />
        </BCSCLoadingProvider>
      </BasicAppContext>
    )

    const inputs = tree.getAllByAccessibilityHint('Enter your 6-digit PIN')
    fireEvent.changeText(inputs[0], '123456')
    fireEvent.changeText(inputs[1], '123456')
    fireEvent.press(tree.getByTestId('com.ariesbifold:id/IUnderstand'))
    fireEvent.press(tree.getByTestId('com.ariesbifold:id/CreatePIN'))

    await waitFor(() => {
      expect(mockOnSuccess).toHaveBeenCalled()
    })

    expect(mockClearPinAttempts).toHaveBeenCalledTimes(1)
    expect(mockSetPIN.mock.invocationCallOrder[0]).toBeLessThan(mockClearPinAttempts.mock.invocationCallOrder[0])
    expect(mockClearPinAttempts.mock.invocationCallOrder[0]).toBeLessThan(mockOnSuccess.mock.invocationCallOrder[0])
  })

  it('shows error when PINs do not match', async () => {
    const tree = render(
      <BasicAppContext>
        <BCSCLoadingProvider>
          <PINEntryForm onSuccess={mockOnSuccess} creatingNewPIN={true} />
        </BCSCLoadingProvider>
      </BasicAppContext>
    )

    const inputs = tree.getAllByAccessibilityHint('Enter your 6-digit PIN')
    fireEvent.changeText(inputs[0], '123456')
    fireEvent.changeText(inputs[1], '654321') // Different

    const checkbox = tree.getByTestId('com.ariesbifold:id/IUnderstand')
    fireEvent.press(checkbox)

    const button = tree.getByTestId('com.ariesbifold:id/CreatePIN')
    fireEvent.press(button)

    await waitFor(() => {
      expect(tree.getByText('BCSC.PIN.PINsDoNotMatch')).toBeTruthy()
    })

    expect(mockSetPIN).not.toHaveBeenCalled()
  })

  it('shows checkbox error when not checked', async () => {
    const tree = render(
      <BasicAppContext>
        <BCSCLoadingProvider>
          <PINEntryForm onSuccess={mockOnSuccess} creatingNewPIN={true} />
        </BCSCLoadingProvider>
      </BasicAppContext>
    )

    const inputs = tree.getAllByAccessibilityHint('Enter your 6-digit PIN')
    fireEvent.changeText(inputs[0], '123456')
    fireEvent.changeText(inputs[1], '123456')

    // Don't check the checkbox

    const button = tree.getByTestId('com.ariesbifold:id/CreatePIN')
    fireEvent.press(button)

    await waitFor(() => {
      expect(tree.getByText('BCSC.PIN.MustCheckBox')).toBeTruthy()
    })

    expect(mockSetPIN).not.toHaveBeenCalled()
  })

  it('shows error when setPIN fails', async () => {
    mockSetPIN.mockResolvedValue({
      success: false,
      walletKey: '',
      isAutoGenerated: false,
    })

    const tree = render(
      <BasicAppContext>
        <BCSCLoadingProvider>
          <PINEntryForm onSuccess={mockOnSuccess} creatingNewPIN={true} />
        </BCSCLoadingProvider>
      </BasicAppContext>
    )

    const inputs = tree.getAllByAccessibilityHint('Enter your 6-digit PIN')
    fireEvent.changeText(inputs[0], '123456')
    fireEvent.changeText(inputs[1], '123456')

    const checkbox = tree.getByTestId('com.ariesbifold:id/IUnderstand')
    fireEvent.press(checkbox)

    const button = tree.getByTestId('com.ariesbifold:id/CreatePIN')
    fireEvent.press(button)

    await waitFor(() => {
      expect(tree.getByText('BCSC.PIN.FailedToSetPIN')).toBeTruthy()
    })

    expect(mockOnSuccess).not.toHaveBeenCalled()
    // The old PIN still stands, and so do the wrong attempts at it
    expect(mockClearPinAttempts).not.toHaveBeenCalled()
  })

  it('shows error when exception is thrown during setPIN', async () => {
    mockSetPIN.mockRejectedValue(new Error('Network error'))

    const tree = render(
      <BasicAppContext>
        <BCSCLoadingProvider>
          <PINEntryForm onSuccess={mockOnSuccess} creatingNewPIN={true} />
        </BCSCLoadingProvider>
      </BasicAppContext>
    )

    const inputs = tree.getAllByAccessibilityHint('Enter your 6-digit PIN')
    fireEvent.changeText(inputs[0], '123456')
    fireEvent.changeText(inputs[1], '123456')

    const checkbox = tree.getByTestId('com.ariesbifold:id/IUnderstand')
    fireEvent.press(checkbox)

    const button = tree.getByTestId('com.ariesbifold:id/CreatePIN')
    fireEvent.press(button)

    await waitFor(() => {
      expect(tree.getByText('BCSC.PIN.ErrorSettingPIN')).toBeTruthy()
    })

    expect(mockOnSuccess).not.toHaveBeenCalled()
  })

  it.each([
    ['first', '123', '654321'],
    ['second', '123456', '123'],
  ])('shows error when %s PIN is too short when pressing Continue', async (_position, pin1, pin2) => {
    const tree = render(
      <BasicAppContext>
        <BCSCLoadingProvider>
          <PINEntryForm onSuccess={mockOnSuccess} creatingNewPIN={true} />
        </BCSCLoadingProvider>
      </BasicAppContext>
    )

    const inputs = tree.getAllByAccessibilityHint('Enter your 6-digit PIN')
    fireEvent.changeText(inputs[0], pin1)
    fireEvent.changeText(inputs[1], pin2)

    const checkbox = tree.getByTestId('com.ariesbifold:id/IUnderstand')
    fireEvent.press(checkbox)

    const button = tree.getByTestId('com.ariesbifold:id/CreatePIN')
    fireEvent.press(button)

    await waitFor(() => {
      expect(tree.getByText('BCSC.PIN.PINTooShort')).toBeTruthy()
    })

    expect(mockSetPIN).not.toHaveBeenCalled()
  })

  /** Fills both PINs, checks the box and presses the main button. */
  const submit = (tree: ReturnType<typeof render>, buttonId: string) => {
    const inputs = tree.getAllByAccessibilityHint('Enter your 6-digit PIN')
    fireEvent.changeText(inputs[0], '123456')
    fireEvent.changeText(inputs[1], '123456')
    fireEvent.press(tree.getByTestId('com.ariesbifold:id/IUnderstand'))
    fireEvent.press(tree.getByTestId(buttonId))
  }

  it('keeps the button spinning once onSuccess resolves when asked to, with the overlay down throughout', async () => {
    let settleSetPIN: (result: Awaited<ReturnType<typeof setPIN>>) => void = () => {}
    mockSetPIN.mockReturnValueOnce(
      new Promise((resolve) => {
        settleSetPIN = resolve
      })
    )

    const tree = render(
      <BasicAppContext>
        <BCSCLoadingProvider>
          <PINEntryForm onSuccess={mockOnSuccess} keepLoadingOnSuccess creatingNewPIN={true} />
        </BCSCLoadingProvider>
      </BasicAppContext>
    )

    submit(tree, 'com.ariesbifold:id/CreatePIN')

    await waitFor(() => {
      expect(mockSetPIN).toHaveBeenCalledWith('123456')
    })
    expect(tree.getByTestId('com.ariesbifold:id/ButtonLoading')).toBeTruthy()
    expect(
      tree.getByTestId('com.ariesbifold:id/BCSCLoadingProviderOverlay', { includeHiddenElements: true }).props
        .accessible
    ).toBe(false)

    await act(async () => {
      settleSetPIN({ success: true, walletKey: 'test-wallet-key', isAutoGenerated: false })
    })

    expect(mockOnSuccess).toHaveBeenCalledWith({ success: true, walletKey: 'test-wallet-key' })
    // The root slides this screen out with the button still spinning
    expect(tree.getByTestId('com.ariesbifold:id/ButtonLoading')).toBeTruthy()
    expect(
      tree.getByTestId('com.ariesbifold:id/BCSCLoadingProviderOverlay', { includeHiddenElements: true }).props
        .accessible
    ).toBe(false)
  })

  it('stops spinning when setting the PIN fails, even when it keeps spinning on success', async () => {
    mockSetPIN.mockResolvedValueOnce({ success: false, walletKey: '', isAutoGenerated: false })

    const tree = render(
      <BasicAppContext>
        <BCSCLoadingProvider>
          <PINEntryForm onSuccess={mockOnSuccess} keepLoadingOnSuccess creatingNewPIN={true} />
        </BCSCLoadingProvider>
      </BasicAppContext>
    )

    submit(tree, 'com.ariesbifold:id/CreatePIN')

    await waitFor(() => {
      expect(tree.getByText('BCSC.PIN.FailedToSetPIN')).toBeTruthy()
    })
    expect(tree.queryByTestId('com.ariesbifold:id/ButtonLoading')).toBeNull()
    expect(tree.getByTestId('com.ariesbifold:id/CreatePIN')).toBeEnabled()
    expect(mockOnSuccess).not.toHaveBeenCalled()
  })

  it('disables the button while it waits, so a second press sets nothing', async () => {
    let settleSetPIN: (result: Awaited<ReturnType<typeof setPIN>>) => void = () => {}
    mockSetPIN.mockReturnValueOnce(
      new Promise((resolve) => {
        settleSetPIN = resolve
      })
    )

    const tree = render(
      <BasicAppContext>
        <BCSCLoadingProvider>
          <PINEntryForm onSuccess={mockOnSuccess} keepLoadingOnSuccess creatingNewPIN={true} />
        </BCSCLoadingProvider>
      </BasicAppContext>
    )

    submit(tree, 'com.ariesbifold:id/CreatePIN')

    await waitFor(() => {
      expect(mockSetPIN).toHaveBeenCalledTimes(1)
    })
    expect(tree.getByTestId('com.ariesbifold:id/CreatePIN')).toBeDisabled()

    fireEvent.press(tree.getByTestId('com.ariesbifold:id/CreatePIN'))
    await act(async () => {
      settleSetPIN({ success: true, walletKey: 'test-wallet-key', isAutoGenerated: false })
    })

    expect(mockSetPIN).toHaveBeenCalledTimes(1)
    expect(mockOnSuccess).toHaveBeenCalledTimes(1)
    // Still disabled while the root slides the screen out
    expect(tree.getByTestId('com.ariesbifold:id/CreatePIN')).toBeDisabled()
  })

  it('waits on the button with the inputs locked and stops spinning once onSuccess resolves, by default', async () => {
    let settleSetPIN: (result: Awaited<ReturnType<typeof setPIN>>) => void = () => {}
    mockSetPIN.mockReturnValueOnce(
      new Promise((resolve) => {
        settleSetPIN = resolve
      })
    )

    const tree = render(
      <BasicAppContext>
        <BCSCLoadingProvider>
          <PINEntryForm onSuccess={mockOnSuccess} />
        </BCSCLoadingProvider>
      </BasicAppContext>
    )

    submit(tree, 'com.ariesbifold:id/Continue')

    await waitFor(() => {
      expect(mockSetPIN).toHaveBeenCalledWith('123456')
    })
    // The screen stays visible, so the navigation inside onSuccess slides from it rather than from
    // behind the overlay
    expect(tree.getByTestId('com.ariesbifold:id/ButtonLoading')).toBeTruthy()
    expect(tree.getByTestId('com.ariesbifold:id/Continue')).toBeDisabled()
    expect(
      tree.getByTestId('com.ariesbifold:id/BCSCLoadingProviderOverlay', { includeHiddenElements: true }).props
        .accessible
    ).toBe(false)
    for (const input of tree.getAllByAccessibilityHint('Enter your 6-digit PIN')) {
      expect(input.props.editable).toBe(false)
    }

    await act(async () => {
      settleSetPIN({ success: true, walletKey: 'test-wallet-key', isAutoGenerated: false })
    })

    expect(mockOnSuccess).toHaveBeenCalledWith({ success: true, walletKey: 'test-wallet-key' })
    expect(tree.queryByTestId('com.ariesbifold:id/ButtonLoading')).toBeNull()
    expect(tree.getByTestId('com.ariesbifold:id/Continue')).toBeEnabled()
    for (const input of tree.getAllByAccessibilityHint('Enter your 6-digit PIN')) {
      expect(input.props.editable).toBe(true)
    }
  })
})
